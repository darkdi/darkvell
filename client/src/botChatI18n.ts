function translateCanonicalBotChat(text: string): string | undefined {
  const fixed = BOT_FIXED_TRANSLATIONS.get(text);
  if (fixed !== undefined) {
    return fixed;
  }

  for (const template of BOT_TEMPLATE_TRANSLATIONS) {
    const match = template.regex.exec(text);
    if (!match) {
      continue;
    }

    let translated = template.english;
    template.placeholders.forEach((placeholder, index) => {
      translated = translated.replaceAll(`{${placeholder}}`, match[index + 1] ?? "");
    });
    return translated;
  }

  return undefined;
}

export function translateBotChat(language: AppLanguage, text: string): string {
  if (language === "ru") {
    return text;
  }

  const fixed = BOT_FIXED_TRANSLATIONS.get(text);
  if (fixed !== undefined) {
    return fixed;
  }

  for (const suffix of BOT_VARIANT_SUFFIX_TRANSLATIONS) {
    const match = suffix.regex.exec(text);
    if (!match) {
      continue;
    }
    const translatedBase = translateCanonicalBotChat(match[1]);
    if (translatedBase !== undefined) {
      return `${translatedBase}${suffix.english(match)}`;
    }
  }

  return translateCanonicalBotChat(text) ?? text;
}
