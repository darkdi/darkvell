type CompiledBotTemplate = {
  regex: RegExp;
  placeholders: readonly string[];
  english: string;
};

function escapeRegex(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function compileBotTemplate([russian, english]: BotChatPair): CompiledBotTemplate {
  const placeholders: string[] = [];
  let cursor = 0;
  let source = "^";

  for (const match of russian.matchAll(/\{([a-z]+)\}/gi)) {
    const index = match.index ?? 0;
    source += escapeRegex(russian.slice(cursor, index));
    source += "(.+?)";
    placeholders.push(match[1]);
    cursor = index + match[0].length;
  }

  source += `${escapeRegex(russian.slice(cursor))}$`;
  return { regex: new RegExp(source, "u"), placeholders, english };
}

const BOT_FIXED_TRANSLATIONS = new Map<string, string>(BOT_FIXED_TRANSLATION_PAIRS);
const BOT_TEMPLATE_TRANSLATIONS = BOT_TEMPLATE_TRANSLATION_PAIRS.map(compileBotTemplate);
const BOT_VARIANT_SUFFIX_TRANSLATIONS: readonly {
  regex: RegExp;
  english: (match: RegExpExecArray) => string;
}[] = [
  {
    regex: /^(.*), я у (.+)$/u,
    english: (match) => {
      const area = match[2];
      const road = /^(.+?) дороги$/u.exec(area);
      return road ? `, I'm by the road near ${road[1]}` : `, I'm near ${area}`;
    }
  },
  { regex: /^(.*), (\d+) лвл если что$/u, english: (match) => `, level ${match[2]} btw` },
  { regex: /^(.*), без суеты$/u, english: () => ", no rush" },
  { regex: /^(.*), аккуратно$/u, english: () => ", careful" },
  { regex: /^(.*), дальше по дороге$/u, english: () => ", farther down the road" },
  { regex: /^(.*), потом в город$/u, english: () => ", then back to town" },
  { regex: /^(.*), если рядом$/u, english: () => ", if you're nearby" },
  { regex: /^(.*), не спешу$/u, english: () => ", taking my time" }
];

