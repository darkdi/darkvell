function interpolate(value: string, vars?: TranslationVars): string {
  if (!vars) {
    return value;
  }
  return value.replace(/\{([a-zA-Z0-9_]+)\}/g, (match, key: string) => String(vars[key] ?? match));
}

function translateRussian(value: string): string {
  const exact = RU_EXACT[value];
  if (exact !== undefined) {
    return exact;
  }
  for (const [pattern, replacement] of RU_PATTERNS) {
    const match = value.match(pattern);
    if (match) {
      return replacement(...match);
    }
  }
  return RU_WORDS.reduce((translated, [pattern, replacement]) => translated.replace(pattern, replacement), value);
}

function translateEnglish(value: string): string {
  const exact = EN_EXACT[value];
  if (exact !== undefined) {
    return exact;
  }
  for (const [pattern, replacement] of EN_PATTERNS) {
    const match = value.match(pattern);
    if (match) {
      return replacement(...match);
    }
  }
  return value;
}

export function translateText(language: AppLanguage, value: string, vars?: TranslationVars): string {
  const translatedTemplate = language === "ru" ? translateRussian(value) : translateEnglish(value);
  return interpolate(translatedTemplate, vars);
}

export function loadLanguage(): AppLanguage {
  if (typeof window === "undefined") {
    return DEFAULT_LANGUAGE;
  }
  try {
    return window.localStorage.getItem(LANGUAGE_STORAGE_KEY) === "en" ? "en" : "ru";
  } catch {
    return DEFAULT_LANGUAGE;
  }
}

export function saveLanguage(language: AppLanguage): void {
  if (typeof window === "undefined") {
    return;
  }
  try {
    window.localStorage.setItem(LANGUAGE_STORAGE_KEY, language);
  } catch {
    // Storage can be unavailable in private WebViews; the in-memory choice still works.
  }
  document.documentElement.lang = language;
}
